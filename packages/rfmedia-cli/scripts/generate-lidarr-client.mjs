function fail(message) {
  throw new Error(message);
}

function toPosixPath(value) {
  return value.split(sep).join("/");
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function gitBlobSha(bytes) {
  return createHash("sha1").update(`blob ${bytes.length}\0`).update(bytes).digest("hex");
}

function readJson(path, label) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    fail(`${label} is not valid JSON.`);
  }
}

function assertObject(value, label) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    fail(`${label} must be an object.`);
  }
  return value;
}

function assertExactKeys(value, expected, label) {
  const keys = Object.keys(assertObject(value, label)).sort();
  const wanted = [...expected].sort();
  if (JSON.stringify(keys) !== JSON.stringify(wanted)) {
    fail(`${label} fields do not match schema version 1.`);
  }
}

function assertString(value, label, pattern) {
  if (typeof value !== "string" || value.length === 0 || (pattern && !pattern.test(value))) {
    fail(`${label} is invalid.`);
  }
  return value;
}

function assertLocalReferences(value) {
  if (Array.isArray(value)) {
    for (const entry of value) assertLocalReferences(entry);
    return;
  }
  if (!value || typeof value !== "object") return;
  for (const [key, entry] of Object.entries(value)) {
    if (key === "$ref" && (typeof entry !== "string" || !entry.startsWith("#/"))) {
      fail("OpenAPI snapshot contains a non-local $ref.");
    }
    assertLocalReferences(entry);
  }
}

function validateSnapshot(packageRoot, manifest) {
  const snapshot = assertObject(manifest.snapshot, "manifest snapshot");
  if (snapshot.path !== "openapi/lidarr-v1.json") fail("Manifest snapshot path is invalid.");
  const snapshotPath = resolve(packageRoot, snapshot.path);
  if (snapshotPath !== resolve(packageRoot, "openapi/lidarr-v1.json")) {
    fail("Manifest snapshot path escapes the package.");
  }
  const bytes = readFileSync(snapshotPath);
  if (bytes.length !== snapshot.size || sha256(bytes) !== snapshot.sha256) {
    fail("OpenAPI snapshot does not match its manifest size and SHA-256.");
  }
  if (gitBlobSha(bytes) !== manifest.upstream.gitBlobSha) {
    fail("OpenAPI snapshot does not match its manifest Git blob SHA.");
  }
  const spec = readJson(snapshotPath, "OpenAPI snapshot");
  if (spec.openapi !== snapshot.openapiVersion || spec.openapi !== "3.0.4") {
    fail("OpenAPI snapshot version does not match the manifest contract.");
  }
  for (const { method, path } of REQUIRED_ENDPOINTS) {
    if (!spec.paths?.[path]?.[method]) {
      fail(`OpenAPI snapshot is missing ${method.toUpperCase()} ${path}.`);
    }
  }
  const schemes = spec.components?.securitySchemes;
  if (
    schemes?.["X-Api-Key"]?.type !== "apiKey" ||
    schemes?.["X-Api-Key"]?.in !== "header" ||
    schemes?.["X-Api-Key"]?.name !== "X-Api-Key" ||
    schemes?.apikey?.type !== "apiKey" ||
    schemes?.apikey?.in !== "query" ||
    schemes?.apikey?.name !== "apikey"
  ) {
    fail("OpenAPI snapshot security schemes do not match the Lidarr contract.");
  }
  assertLocalReferences(spec);
}

function findLockfile(packageRoot) {
  let directory = packageRoot;
  while (true) {
    const candidate = join(directory, "package-lock.json");
    try {
      const lock = readJson(candidate, "package lockfile");
      const workspace = toPosixPath(relative(directory, packageRoot));
      if (lock.packages?.[workspace]) return { lock, lockRoot: directory, workspace };
    } catch (error) {
      if (!(error instanceof Error) || !error.message.includes("ENOENT")) {
        // A malformed nearest lockfile is a validation failure, not a reason to search upward.
        if (statExists(candidate)) throw error;
      }
    }
    const parent = dirname(directory);
    if (parent === directory) fail("Unable to locate the workspace package lockfile.");
    directory = parent;
  }
}

function statExists(path) {
  try {
    lstatSync(path);
    return true;
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
}

function validateToolchain(packageRoot, manifest) {
  const generator = assertObject(manifest.generator, "manifest generator");
  if (generator.package !== "@hey-api/openapi-ts" || generator.version !== "0.93.0") {
    fail("Manifest generator identity must be @hey-api/openapi-ts@0.93.0.");
  }
  const packageJson = readJson(join(packageRoot, "package.json"), "rfmedia package.json");
  if (packageJson.devDependencies?.[generator.package] !== generator.version) {
    fail("rfmedia must exact-pin the manifest generator version.");
  }
  const require = createRequire(pathToFileURL(join(packageRoot, "package.json")));
  const installed = readJson(
    require.resolve(`${generator.package}/package.json`),
    "installed generator",
  );
  if (installed.version !== generator.version)
    fail("Installed generator version does not match manifest.");

  const { lock, workspace } = findLockfile(packageRoot);
  const workspaceRecord = lock.packages[workspace];
  const toolRecord = lock.packages[`node_modules/${generator.package}`];
  if (
    workspaceRecord.devDependencies?.[generator.package] !== generator.version ||
    toolRecord?.version !== generator.version ||
    toolRecord?.resolved !== generator.tarball ||
    toolRecord?.integrity !== generator.integrity ||
    toolRecord?.dev !== true
  ) {
    fail("Lockfile generator identity does not match the manifest.");
  }
}

function validateManifestShape(manifest) {
  assertExactKeys(
    manifest,
    ["schemaVersion", "upstream", "snapshot", "generator", "bundledClient", "normalization"],
    "manifest",
  );
  if (manifest.schemaVersion !== 1) fail("Unsupported Lidarr manifest schema version.");
  assertExactKeys(
    manifest.upstream,
    ["repository", "commit", "path", "url", "gitBlobSha"],
    "manifest upstream",
  );
  assertExactKeys(
    manifest.snapshot,
    ["path", "sha256", "size", "openapiVersion"],
    "manifest snapshot",
  );
  assertExactKeys(
    manifest.generator,
    ["package", "version", "tarball", "integrity", "config"],
    "manifest generator",
  );
  assertExactKeys(
    manifest.generator.config,
    [
      "path",
      "version",
      "input",
      "output",
      "tsConfig",
      "importFileExtension",
      "sdkScope",
      "sdkOperations",
      "sdkClient",
      "generatedAuth",
    ],
    "manifest generator config",
  );
  assertExactKeys(
    manifest.bundledClient,
    ["plugin", "versionIdentity", "bundle", "provenance"],
    "manifest bundled client",
  );
  assertExactKeys(
    manifest.bundledClient.provenance,
    [
      "sourcePackage",
      "sourceVersion",
      "sourceTarball",
      "sourceIntegrity",
      "rawFileSha256",
      "normalizedFileSha256",
    ],
    "manifest bundled provenance",
  );
  assertExactKeys(
    manifest.normalization,
    ["version", "file", "search", "replacement", "expectedMatches", "failureMode"],
    "manifest normalization",
  );

  const upstream = manifest.upstream;
  const commit = assertString(upstream.commit, "manifest commit", /^[a-f0-9]{40}$/);
  if (
    upstream.repository !== "Lidarr/Lidarr" ||
    upstream.path !== "src/Lidarr.Api.V1/openapi.json"
  ) {
    fail("Manifest upstream repository or path is not allowlisted.");
  }
  const expectedUrl = `https://raw.githubusercontent.com/Lidarr/Lidarr/${commit}/${upstream.path}`;
  if (upstream.url !== expectedUrl) fail("Manifest upstream URL is not pinned to its full commit.");
  assertString(upstream.gitBlobSha, "manifest Git blob SHA", /^[a-f0-9]{40}$/);
  assertString(manifest.snapshot.sha256, "manifest snapshot SHA-256", /^[a-f0-9]{64}$/);
  if (!Number.isSafeInteger(manifest.snapshot.size) || manifest.snapshot.size <= 0) {
    fail("Manifest snapshot size is invalid.");
  }
  const config = manifest.generator.config;
  const expectedConfig = {
    path: CONFIG_RELATIVE_PATH,
    version: 1,
    input: "openapi/lidarr-v1.json",
    output: GENERATED_RELATIVE_PATH,
    tsConfig: "tsconfig.json",
    importFileExtension: ".js",
    sdkScope: "full-private",
    sdkOperations: "flat",
    sdkClient: false,
    generatedAuth: false,
  };
  if (JSON.stringify(config) !== JSON.stringify(expectedConfig))
    fail("Manifest generator config drift detected.");
  const bundled = manifest.bundledClient;
  const provenance = bundled.provenance;
  if (
    bundled.plugin !== "@hey-api/client-fetch" ||
    bundled.versionIdentity !==
      `bundled-with-${manifest.generator.package}@${manifest.generator.version}` ||
    bundled.bundle !== true ||
    provenance.sourcePackage !== manifest.generator.package ||
    provenance.sourceVersion !== manifest.generator.version ||
    provenance.sourceTarball !== manifest.generator.tarball ||
    provenance.sourceIntegrity !== manifest.generator.integrity
  ) {
    fail("Bundled client provenance does not match the generator identity.");
  }
  assertExactKeys(provenance.rawFileSha256, BUNDLED_RUNTIME_FILES, "raw bundled runtime hashes");
  assertExactKeys(
    provenance.normalizedFileSha256,
    ["client/client.gen.ts"],
    "normalized bundled runtime hashes",
  );
  for (const [path, digest] of Object.entries(provenance.rawFileSha256)) {
    assertString(digest, `raw bundled runtime hash ${path}`, /^[a-f0-9]{64}$/);
  }
  assertString(
    provenance.normalizedFileSha256["client/client.gen.ts"],
    "normalized bundled runtime hash",
    /^[a-f0-9]{64}$/,
  );
  const normalization = manifest.normalization;
  if (
    normalization.version !== 1 ||
    normalization.file !== "client/client.gen.ts" ||
    normalization.search !== "BodyInit" ||
    normalization.replacement !== "RequestInit['body']" ||
    normalization.expectedMatches !== 2 ||
    normalization.failureMode !== "reject-unless-exact"
  ) {
    fail("Manifest normalization contract drift detected.");
  }
}

