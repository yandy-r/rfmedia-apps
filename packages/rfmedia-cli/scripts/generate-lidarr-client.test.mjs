function digest(bytes, algorithm = "sha256") {
  return createHash(algorithm).update(bytes).digest("hex");
}

function blobDigest(bytes) {
  return createHash("sha1").update(`blob ${bytes.length}\0`).update(bytes).digest("hex");
}

function createEndpointMap(endpoints) {
  const paths = {};
  for (const [method, path] of endpoints) {
    paths[path] ??= {};
    paths[path][method] = { responses: { 200: { description: "ok" } } };
  }
  return paths;
}

function withoutOperation(files, operation) {
  const declaration = `export const ${operation} = () => undefined;\n`;
  return { ...files, "sdk.gen.ts": files["sdk.gen.ts"].replace(declaration, "") };
}

function withoutRequestEnvelope(files, envelope) {
  const declaration = `export type ${envelope} = { url: string };\n`;
  return { ...files, "types.gen.ts": files["types.gen.ts"].replace(declaration, "") };
}

function write(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

function createRawTree(bodyInitMatches = 2) {
  const files = Object.fromEntries(RUNTIME_FILES.map((path) => [path, `${HEADER}export {};\n`]));
  files["client/client.gen.ts"] = `${HEADER}${Array.from(
    { length: bodyInitMatches },
    (_, index) => `const body${index} = value as BodyInit | null | undefined;`,
  ).join("\n")}\n`;
  files["client.gen.ts"] = `${HEADER}export {};\n`;
  files["index.ts"] = `${HEADER}export {};\n`;
  files["types.gen.ts"] = `${HEADER}${REQUIRED_REQUEST_ENVELOPES.map(
    (name) => `export type ${name} = { url: string };`,
  ).join("\n")}\n`;
  files["sdk.gen.ts"] = `${HEADER}${REQUIRED_OPERATIONS.map(
    (name) => `export const ${name} = () => undefined;`,
  ).join("\n")}\n`;
  return files;
}

function writeTree(root, files) {
  for (const [path, content] of Object.entries(files)) write(join(root, path), content);
}

function snapshotTree(root) {
  const result = [];
  const visit = (directory) => {
    for (const entry of readdirSync(directory, { withFileTypes: true }).sort((a, b) =>
      a.name.localeCompare(b.name),
    )) {
      const absolute = join(directory, entry.name);
      const path = relative(root, absolute);
      const stat = lstatSync(absolute);
      result.push(
        `${path}:${stat.isFile() ? digest(readFileSync(absolute)) : stat.isDirectory() ? "directory" : "other"}`,
      );
      if (stat.isDirectory()) visit(absolute);
    }
  };
  visit(root);
  return result;
}

