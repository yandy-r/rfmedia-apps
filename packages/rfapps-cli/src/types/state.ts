/**
 * State types for rfapps CLI.
 *
 * Types for deployment history tracking and rollback capabilities.
 * State is persisted in SQLite following XDG Base Directory Specification:
 * - Default: ~/.config/rfapps/state.db
 * - Legacy: ~/.rfapps/state.db (if directory exists)
 *
 * Schema overview:
 * - `deployments` table: Stores deployment records with service, action, image, status
 * - `generations` table: Immutable per-service generation snapshots (Nix-style)
 * - `metadata` table: Stores schema_version for migrations
 *
 * Key types:
 * - {@link StateEntry}: Full deployment record (read from database)
 * - {@link StateEntryInput}: Deployment record for insertion (without auto-generated ID)
 * - {@link ConfigSnapshot}: Service configuration captured at deployment time
 * - {@link GenerationEntry}: Immutable generation snapshot (read from database)
 * - {@link HistoryOptions}: Query filters for deployment history
 * - {@link RollbackOptions}: Options for rollback command
 */

/**
 * Type of deployment action that was performed.
 *
 * - `deploy`: Initial deployment or update of a service
 * - `rebuild`: Stop + build + start a service
 * - `delete`: Remove a service (container only or with volumes/images)
 * - `rollback`: Restore a service to a previous deployment state
 * - `apply`: Execute a saved deployment plan
 * - `prune`: Remove a service and clean up unused images
 * - `update`: Apply a verified managed image update
 * - `import`: Adopt an externally-created running service as a baseline snapshot
 */
export type DeploymentAction =
  | "deploy"
  | "rebuild"
  | "delete"
  | "rollback"
  | "apply"
  | "prune"
  | "update"
  | "import";

/**
 * Status of a deployment operation.
 *
 * - `success`: Deployment completed successfully
 * - `failed`: Deployment failed (error message in errorMessage field)
 * - `rolled_back`: Deployment was later rolled back to a previous state
 */
export type DeploymentStatus = "success" | "failed" | "rolled_back";

/**
 * Configuration snapshot stored for rollback capability.
 *
 * Captures the service configuration at deployment time, enabling
 * restoration to a known-good state. Sensitive environment variables
 * are masked before storage using {@link maskSensitiveEnvVars}.
 *
 * Stored as JSON string in the `config_snapshot` column of deployments table.
 */
export interface ConfigSnapshot {
  /** Full image reference with tag */
  image: string;
  /** Environment variables (sensitive values masked) */
  environment: Record<string, string>;
  /** Volume mounts */
  volumes: string[];
  /** Port mappings */
  ports: string[];
  /** Network connections */
  networks: string[];
  /** Container labels */
  labels: Record<string, string>;
}

/**
 * A single deployment state entry.
 *
 * Represents a deployment record as returned from database queries.
 * The ID is auto-generated by SQLite. Timestamps are ISO 8601 format.
 */
export interface StateEntry {
  /** Unique identifier for the deployment record */
  id: number;
  /** ISO 8601 timestamp of the deployment */
  timestamp: string;
  /** Name of the service deployed */
  service: string;
  /** Type of action performed */
  action: DeploymentAction;
  /** Image tag used (if applicable) */
  imageTag?: string;
  /** Immutable daemon-local image ID (if observed) */
  imageId?: string;
  /** Canonical repository digest (if observed) */
  imageDigest?: string;
  /** JSON snapshot of service configuration at deployment time */
  configSnapshot?: string;
  /** Status of the deployment */
  status: DeploymentStatus;
  /** Reference to plan ID if deployment was from apply command */
  planId?: string;
  /** Error message if deployment failed */
  errorMessage?: string;
}

/**
 * Raw database row for StateEntry.
 *
 * Represents the raw row structure from better-sqlite3 queries before
 * transformation to {@link StateEntry}. Uses snake_case column names
 * matching the SQLite schema and nullable types for optional columns.
 */
export interface StateEntryRow {
  /** Unique identifier */
  id: number;
  /** ISO 8601 timestamp */
  timestamp: string;
  /** Service name */
  service: string;
  /** Action type as string */
  action: string;
  /** Image tag (nullable in DB) */
  image_tag: string | null;
  /** Immutable daemon-local image ID (nullable in DB) */
  image_id?: string | null;
  /** Canonical repository digest (nullable in DB) */
  image_digest?: string | null;
  /** Config snapshot JSON (nullable in DB) */
  config_snapshot: string | null;
  /** Status as string */
  status: string;
  /** Plan ID (nullable in DB) */
  plan_id: string | null;
  /** Error message (nullable in DB) */
  error_message: string | null;
}

/**
 * Deployment actions that produce a generation snapshot.
 *
 * Destructive actions (`delete`, `prune`) do not create generations because
 * the service no longer has a running configuration to snapshot.
 */
export type GenerationAction = "deploy" | "rebuild" | "apply" | "rollback" | "update" | "import";

/**
 * An immutable generation snapshot for a service.
 *
 * Generations follow the Nix model of generational state: every successful
 * deploy-like action appends a new numbered generation per service. Entries
 * are append-only — the CLI never updates or deletes them — which makes them
 * reliable restore targets even after the originating deployment record's
 * status changes.
 *
 * Scope: a generation records the image reference and a config snapshot for audit.
 * Restoring applies the image only — config comes from the current compose file,
 * and volumes/databases are never rolled back.
 */
export interface GenerationEntry {
  /** Unique row identifier (global, auto-generated) */
  id: number;
  /** Name of the service this generation belongs to */
  service: string;
  /** Per-service generation number (1, 2, 3, ...) */
  generation: number;
  /** ID of the deployment record that created this generation */
  deploymentId?: number;
  /** ISO 8601 timestamp when the generation was created */
  timestamp: string;
  /** Image tag captured at deployment time */
  imageTag?: string;
  /** Immutable daemon-local image ID captured at deployment time */
  imageId?: string;
  /** Canonical repository digest captured at deployment time */
  imageDigest?: string;
  /** JSON snapshot of service configuration at deployment time */
  configSnapshot?: string;
  /** Action that created this generation */
  createdByAction: GenerationAction;
}

/**
 * Raw database row for GenerationEntry.
 *
 * Uses snake_case column names matching the SQLite schema and nullable
 * types for optional columns.
 */
export interface GenerationRow {
  /** Unique row identifier */
  id: number;
  /** Service name */
  service: string;
  /** Per-service generation number */
  generation: number;
  /** Originating deployment ID (nullable in DB) */
  deployment_id: number | null;
  /** ISO 8601 timestamp */
  timestamp: string;
  /** Image tag (nullable in DB) */
  image_tag: string | null;
  /** Immutable daemon-local image ID (nullable in DB) */
  image_id?: string | null;
  /** Canonical repository digest (nullable in DB) */
  image_digest?: string | null;
  /** Config snapshot JSON (nullable in DB) */
  config_snapshot: string | null;
  /** Action that created this generation */
  created_by_action: string;
}

/**
 * Input for recording a new generation.
 *
 * Same as {@link GenerationEntry} but without `id` (auto-generated by SQLite)
 * and `generation` (computed as the next per-service number on insert).
 */
export type GenerationInput = Omit<GenerationEntry, "id" | "generation">;

/**
 * Options for querying generations.
 */
export interface GenerationsOptions {
  /** Filter by service name */
  service?: string;
  /** Maximum number of entries to return (default: 10) */
  limit?: number;
}

/**
 * Result of a generations query for JSON output.
 */
export interface GenerationsResult {
  /** Queried generation entries (newest first) */
  entries: GenerationEntry[];
  /** Total count matching filters (may differ from entries.length if limited) */
  totalCount: number;
  /** Filters that were applied */
  filters: {
    service?: string;
    limit: number;
  };
}

/**
 * Options for querying deployment history.
 *
 * All fields are optional. When omitted, defaults are applied:
 * - No service filter (all services)
 * - No action filter (all actions)
 * - No date filter (all time)
 * - limit: 10 entries
 */
export interface HistoryOptions {
  /** Filter by service name */
  service?: string;
  /** Maximum number of entries to return (default: 10) */
  limit?: number;
  /** Filter entries after this ISO 8601 timestamp */
  since?: string;
  /** Filter by action type */
  action?: DeploymentAction;
}

/**
 * Options for rollback command.
 *
 * Target selection (mutually exclusive): `steps`, `toDeployment`,
 * `toGeneration`, or `toTime`. If none is provided, defaults to rolling
 * back 1 step (previous deployment).
 *
 * Restore scope: rollback restores the service image only; config comes from the current compose file.
 * Volumes and databases are never rolled back.
 */
export interface RollbackOptions {
  /** Service to rollback (required) */
  service: string;
  /** Number of deployments to rollback (default: 1) */
  steps?: number;
  /** Rollback to a specific deployment ID */
  toDeployment?: number;
  /** Restore to a specific generation number (from `rfapps history --generations`) */
  toGeneration?: number;
  /** Restore to the generation that was active at this ISO 8601 time */
  toTime?: string;
  /** Skip validation warnings and allow recreating deleted services */
  force: boolean;
  /** Preview what would be rolled back without executing */
  dryRun: boolean;
  /** Skip confirmation prompt */
  yes: boolean;
}

/**
 * Configuration for state persistence.
 *
 * Controls where the state database is stored and whether state
 * recording is enabled. Can be configured via:
 * - Config file: `state.dbPath` and `state.enabled` in .rfapps.yaml
 * - Environment: `RFAPPS_STATE_DB_PATH` and `RFAPPS_STATE_ENABLED`
 */
export interface StateConfig {
  /** Path to state database file (default: ~/.rfapps/state.db) */
  dbPath?: string;
  /** Whether state recording is enabled (default: true) */
  enabled?: boolean;
}

/**
 * Input for recording a new deployment.
 *
 * Same as {@link StateEntry} but without the `id` field, which is
 * auto-generated by SQLite on insert.
 */
export type StateEntryInput = Omit<StateEntry, "id">;

/** Non-fatal warning retained for rollback audit output. */
export interface RollbackWarning {
  /** Stable machine-readable warning category. */
  code: "TEMP_OVERRIDE_CLEANUP_FAILED";
  /** Safe operator-facing diagnostic. */
  message: string;
  /** Private temporary directory retained for manual cleanup. */
  temporaryDirectory: string;
}

/**
 * Result of a rollback operation.
 *
 * Used for JSON output mode. Contains both success/failure status
 * and relevant IDs for auditing and debugging.
 */
export interface RollbackResult {
  /** Whether the rollback succeeded */
  success: boolean;
  /** Service that was rolled back */
  service: string;
  /** Deployment ID that was the rollback target */
  targetDeploymentId: number;
  /** Generation number that was the restore target (when restoring by generation/time) */
  targetGeneration?: number;
  /** New deployment ID created for the rollback action */
  rollbackDeploymentId?: number;
  /** Error message if rollback failed */
  errorMessage?: string;
  /** Image tag that was restored */
  restoredImageTag?: string;
  /** Non-fatal diagnostics that did not change the verified rollback outcome. */
  warnings?: RollbackWarning[];
}

/**
 * Result of history query for JSON output.
 *
 * Includes the queried entries, total count (may differ from entries.length
 * if limited), and the filters that were applied.
 */
export interface HistoryResult {
  /** Queried entries */
  entries: StateEntry[];
  /** Total count matching filters (may differ from entries.length if limited) */
  totalCount: number;
  /** Filters that were applied */
  filters: {
    service?: string;
    action?: DeploymentAction;
    since?: string;
    limit: number;
  };
}
